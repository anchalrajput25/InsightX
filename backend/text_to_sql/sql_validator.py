# ============================================================
# SQL VALIDATOR
# ============================================================
#
# Purpose:
#   Validate SQL generated by the SQL Generator before execution.
#
# Supports:
#   - arbitrary PostgreSQL databases
#   - CTEs
#   - multiple CTEs
#   - nested subqueries
#   - correlated subqueries
#   - multi-hop JOINs
#   - GROUP BY / HAVING
#   - window functions
#   - UNION / UNION ALL
#   - INTERSECT
#   - EXCEPT
#   - PostgreSQL functions
#   - date/time operations
#   - aliases
#   - complex analytical SQL
#
# Database-agnostic:
#   - No hardcoded table names
#   - No hardcoded column names
#   - No hardcoded schema
#   - Tables are discovered dynamically
#   - CTEs are detected dynamically
#
# ============================================================


# ============================================================
# CONSTANTS
# ============================================================

ALLOWED_ROOT_EXPRESSIONS = (
    exp.Select,
    exp.Union,
    exp.Intersect,
    exp.Except,
)

FORBIDDEN_DML_EXPRESSIONS = (
    exp.Insert,
    exp.Update,
    exp.Delete,
    exp.Create,
    exp.Drop,
    exp.Alter,
)


# ============================================================
# RESULT OBJECT
# ============================================================

def validation_result(
    valid: bool,
    status: str,
    reason: str = "",
    errors: Optional[list[str]] = None,
    warnings: Optional[list[str]] = None,
    details: Optional[Dict[str, Any]] = None,
) -> Dict[str, Any]:

    return {
        "valid": valid,
        "status": status,
        "reason": reason,
        "errors": errors or [],
        "warnings": warnings or [],
        "details": details or {},
    }


# ============================================================
# SQL CLEANING
# ============================================================

def clean_sql(sql: str) -> str:
    """
    Remove Markdown code fences and unnecessary whitespace.
    """

    if not isinstance(sql, str):
        return ""

    sql = sql.strip()

    sql = re.sub(
        r"^```(?:sql|postgresql)?\s*",
        "",
        sql,
        flags=re.IGNORECASE,
    )

    sql = re.sub(
        r"\s*```$",
        "",
        sql,
        flags=re.IGNORECASE,
    )

    return sql.strip()


# ============================================================
# MULTIPLE STATEMENT CHECK
# ============================================================

def has_multiple_statements(sql: str) -> bool:
    """
    Allow one optional trailing semicolon.

    Valid:

        SELECT * FROM users;

    Invalid:

        SELECT * FROM users;
        SELECT * FROM orders;
    """

    sql = clean_sql(sql)

    if not sql:
        return False

    without_trailing = sql.rstrip(";").strip()

    return ";" in without_trailing


# ============================================================
# PARSE SQL
# ============================================================

def parse_sql(sql: str):
    """
    Parse PostgreSQL SQL using SQLGlot.
    """

    try:
        return sqlglot.parse_one(
            sql,
            read=dialects.sqlglot_name(),
        )

    except Exception as exc:

        raise ValueError(
            f"{dialects.label()} SQL parsing failed: {exc}"
        ) from exc


# ============================================================
# ROOT QUERY CHECK
# ============================================================

def validate_root_query(ast) -> tuple[bool, str]:
    """
    Ensure the generated query is fundamentally a read query.

    Complex SELECT structures are allowed.
    """

    if isinstance(ast, ALLOWED_ROOT_EXPRESSIONS):
        return True, ""

    if isinstance(ast, exp.Subquery):

        inner = ast.this

        if isinstance(inner, ALLOWED_ROOT_EXPRESSIONS):
            return True, ""

    return (
        False,
        f"Unsupported root SQL expression: "
        f"{type(ast).__name__}",
    )


# ============================================================
# DML / DDL CHECK
# ============================================================

def find_forbidden_operations(ast) -> list[str]:
    """
    Detect DML/DDL anywhere in the parsed SQL tree.

    InsightX is a read-oriented Text-to-SQL system, so
    write/destructive operations are rejected.
    """

    found = []

    for node in ast.walk():

        if isinstance(node, exp.Insert):
            found.append("INSERT")

        elif isinstance(node, exp.Update):
            found.append("UPDATE")

        elif isinstance(node, exp.Delete):
            found.append("DELETE")

        elif isinstance(node, exp.Create):
            found.append("CREATE")

        elif isinstance(node, exp.Drop):
            found.append("DROP")

        elif isinstance(node, exp.Alter):
            found.append("ALTER")

    return sorted(set(found))


# ============================================================
# CTE EXTRACTION
# ============================================================

def extract_ctes(ast) -> list[str]:
    """
    Dynamically extract CTE names.

    CTEs are temporary query-level relations.
    They are NOT physical database tables.
    """

    ctes = set()

    for cte in ast.find_all(exp.CTE):

        alias = cte.alias_or_name

        if alias:
            ctes.add(alias)

    return sorted(ctes)


# ============================================================
# TABLE EXTRACTION
# ============================================================

def extract_tables(ast) -> list[str]:
    """
    Extract physical database table references.

    Completely database-agnostic.

    Supports:
        - arbitrary PostgreSQL databases
        - CTEs
        - nested queries
        - JOINs
        - schema-qualified tables
        - quoted identifiers
        - table aliases

    CTE references are excluded because CTEs are not
    physical database tables.
    """

    # --------------------------------------------------------
    # Discover CTE names dynamically
    # --------------------------------------------------------

    cte_names = {
        cte.alias_or_name.lower()
        for cte in ast.find_all(exp.CTE)
        if cte.alias_or_name
    }

    tables = set()

    # --------------------------------------------------------
    # Find all table nodes
    # --------------------------------------------------------

    for table in ast.find_all(exp.Table):

        table_name = table.name

        if not table_name:
            continue

        # ----------------------------------------------------
        # Ignore references to CTEs
        # ----------------------------------------------------

        if table_name.lower() in cte_names:
            continue

        tables.add(table_name)

    return sorted(tables)


# ============================================================
# COLUMN EXTRACTION
# ============================================================

def extract_columns(ast) -> list[str]:
    """
    Extract column references.

    Used mainly for diagnostics and observability.

    PostgreSQL EXPLAIN remains the stronger semantic check.
    """

    columns = set()

    for column in ast.find_all(exp.Column):

        name = column.name

        if name:
            columns.add(name)

    return sorted(columns)


# ============================================================
# JOIN EXTRACTION
# ============================================================

def extract_joins(ast) -> list[str]:
    """
    Extract JOIN types for observability.
    """

    joins = []

    for join in ast.find_all(exp.Join):

        kind = join.args.get("kind")

        if kind:
            joins.append(str(kind).upper())
        else:
            joins.append("JOIN")

    return joins


# ============================================================
# AGGREGATION DETECTION
# ============================================================

def contains_aggregation(ast) -> bool:
    """
    Detect aggregate functions.
    """

    aggregate_types = (
        exp.Sum,
        exp.Avg,
        exp.Count,
        exp.Min,
        exp.Max,
    )

    return any(
        isinstance(node, aggregate_types)
        for node in ast.walk()
    )


# ============================================================
# WINDOW FUNCTION DETECTION
# ============================================================

def contains_window_function(ast) -> bool:
    """
    Detect SQL window functions.
    """

    return any(
        isinstance(node, exp.Window)
        for node in ast.walk()
    )


# ============================================================
# SUBQUERY DETECTION
# ============================================================

def contains_subquery(ast) -> bool:
    """
    Detect nested subqueries.

    Note:
        CTEs are not counted as ordinary subqueries here.
    """

    return any(
        isinstance(node, exp.Subquery)
        for node in ast.walk()
    )


# ============================================================
# SET OPERATIONS
# ============================================================

def extract_set_operations(ast) -> list[str]:
    """
    Detect UNION / INTERSECT / EXCEPT.
    """

    operations = set()

    for node in ast.walk():

        if isinstance(node, exp.Union):
            operations.add("UNION")

        elif isinstance(node, exp.Intersect):
            operations.add("INTERSECT")

        elif isinstance(node, exp.Except):
            operations.add("EXCEPT")

    return sorted(operations)


# ============================================================
# DATABASE TABLE DISCOVERY
# ============================================================

def get_database_tables(
    engine: Engine,
) -> set[str]:
    """
    Dynamically discover physical tables from the connected
    PostgreSQL database.

    No business-specific table names are used.
    """

    inspector = inspect(engine)

    # LangGraph checkpoint tables are not queryable business data.
    return set(
        filter_business_tables(
            inspector,
            inspector.get_table_names(),
        )
    )


# ============================================================
# MISSING TABLE CHECK
# ============================================================

def find_missing_tables(
    tables: list[str],
    engine: Engine,
) -> list[str]:
    """
    Referenced physical tables that do not exist in the connected
    database. Raises if the database cannot be inspected, so the
    caller reports a validation failure instead of silently skipping
    the check.
    """

    existing_tables_lower = {
        table.lower()
        for table in get_database_tables(engine)
    }

    return sorted({
        table
        for table in tables
        if table.lower() not in existing_tables_lower
    })


# ============================================================
# POSTGRESQL EXPLAIN VALIDATION
# ============================================================

def postgres_explain_validation(
    sql: str,
    engine: Engine,
) -> Dict[str, Any]:
    """
    Ask PostgreSQL to PLAN the query without executing it.

    PostgreSQL can catch issues such as:

        - relation does not exist
        - column does not exist
        - ambiguous column
        - invalid GROUP BY
        - invalid JOIN references
        - invalid PostgreSQL syntax
        - invalid functions/operators
        - invalid type relationships
        - invalid aliases
        - invalid CTE references
        - invalid nested-query references

    EXPLAIN validates query planning.
    It does not execute the SELECT itself.
    """

    try:

        # Same guarded path as execution: read-only transaction with
        # statement_timeout, and no text() bind-parameter parsing.
        with read_only_connection(engine) as connection:
            dialects.check_plan(
                connection,
                driver_sql(sql.rstrip().rstrip(";"), engine),
            )

        return {
            "valid": True,
            "error": None,
        }

    except Exception as exc:

        return {
            "valid": False,
            "error": str(getattr(exc, "orig", None) or exc).strip(),
        }


# ============================================================
# MAIN VALIDATOR
# ============================================================

def validate_sql(
    sql: str,
    engine: Optional[Engine] = None,
    run_explain: bool = True,
    check_values: bool = True,
) -> Dict[str, Any]:
    """
    Main SQL validation pipeline.

    Parameters
    ----------
    sql:
        SQL generated by sql_generator.py.

    engine:
        SQLAlchemy PostgreSQL engine.

        Required when run_explain=True.

    run_explain:
        Whether PostgreSQL should validate the query plan.

    Returns
    -------
    Dictionary containing:

        valid
        status
        reason
        errors
        warnings
        details
    """

    # ========================================================
    # 1. INPUT
    # ========================================================

    sql = clean_sql(sql)

    if not sql:

        return validation_result(
            valid=False,
            status="INVALID",
            reason="SQL is empty.",
            errors=[
                "Empty SQL query."
            ],
        )

    # ========================================================
    # 2. MULTIPLE STATEMENTS
    # ========================================================

    if has_multiple_statements(sql):

        return validation_result(
            valid=False,
            status="INVALID",
            reason="Multiple SQL statements detected.",
            errors=[
                "Only one SQL statement is allowed."
            ],
        )

    # ========================================================
    # 3. PARSE SQL
    # ========================================================

    try:

        ast = parse_sql(sql)

    except ValueError as exc:

        return validation_result(
            valid=False,
            status="INVALID",
            reason="SQL parsing failed.",
            errors=[
                str(exc)
            ],
        )

    # ========================================================
    # 4. ROOT QUERY
    # ========================================================

    root_valid, root_reason = validate_root_query(
        ast
    )

    if not root_valid:

        return validation_result(
            valid=False,
            status="INVALID",
            reason=root_reason,
            errors=[
                root_reason
            ],
        )

    # ========================================================
    # 5. FORBIDDEN OPERATIONS
    # ========================================================

    forbidden = find_forbidden_operations(
        ast
    )

    if forbidden:

        return validation_result(
            valid=False,
            status="INVALID",
            reason=(
                "Read-only Text-to-SQL query expected, "
                "but write/DDL operation detected."
            ),
            errors=[
                "Forbidden operations: "
                + ", ".join(forbidden)
            ],
        )

    # ========================================================
    # 6. QUERY METADATA
    # ========================================================

    tables = extract_tables(ast)

    columns = extract_columns(ast)

    ctes = extract_ctes(ast)

    joins = extract_joins(ast)

    set_operations = extract_set_operations(
        ast
    )

    has_aggregation = contains_aggregation(
        ast
    )

    has_window = contains_window_function(
        ast
    )

    has_subquery = contains_subquery(
        ast
    )

    details = {
        "tables": tables,
        "columns": columns,
        "ctes": ctes,
        "joins": joins,
        "set_operations": set_operations,
        "has_aggregation": has_aggregation,
        "has_window_function": has_window,
        "has_subquery": has_subquery,
    }

    # ========================================================
    # 7. DYNAMIC DATABASE SCHEMA CHECK
    # ========================================================

    warnings = []

    if engine is not None:

        try:
            missing_tables = find_missing_tables(
                tables,
                engine,
            )
        except Exception as exc:
            return validation_result(
                valid=False,
                status="INVALID",
                reason="Could not inspect database tables.",
                errors=[
                    f"Table inspection failed: {exc}"
                ],
                details=details,
            )

        if missing_tables:

            return validation_result(
                valid=False,
                status="INVALID",
                reason="Referenced table does not exist.",
                errors=[
                    "Missing tables: "
                    + ", ".join(missing_tables)
                ],
                details=details,
            )

    else:

        warnings.append(
            "Database schema check was skipped because "
            "no database engine was provided."
        )

    # ========================================================
    # 8. POSTGRESQL EXPLAIN
    # ========================================================

    if run_explain:

        if engine is None:

            warnings.append(
                "PostgreSQL EXPLAIN was skipped because "
                "no database engine was provided."
            )

        else:

            explain_result = (
                postgres_explain_validation(
                    sql,
                    engine,
                )
            )

            details["postgres_explain"] = (
                explain_result
            )

            if not explain_result["valid"]:

                return validation_result(
                    valid=False,
                    status="INVALID",
                    reason=(
                        "PostgreSQL rejected the query "
                        "during planning."
                    ),
                    errors=[
                        explain_result["error"]
                    ],
                    warnings=warnings,
                    details=details,
                )

    # ========================================================
    # 9. SUCCESS
    # ========================================================

    # --------------------------------------------------------
    # FILTER VALUES EXIST IN THE DATA
    # --------------------------------------------------------
    #
    # Catches valid SQL that would silently return nothing because a
    # literal does not match the stored value (e.g. 'São Paulo' vs
    # 'sao paulo').

    if engine is not None and check_values:

        try:
            value_check = check_filter_values(
                ast,
                engine,
            )
        except Exception as exc:
            value_check = None
            warnings.append(
                f"Filter value check skipped: {exc}"
            )

        if value_check is not None:

            details["value_check"] = value_check

            if value_check["issues"]:
                return validation_result(
                    valid=False,
                    status="INVALID",
                    reason=(
                        "A filter value does not exist in the data; "
                        "similar stored values were found."
                    ),
                    errors=[
                        issue["message"]
                        for issue in value_check["issues"]
                    ],
                    warnings=warnings,
                    details=details,
                )

            warnings.extend(
                item["message"]
                for item in value_check["unmatched"]
            )

    return validation_result(
        valid=True,
        status="VALID",
        reason=(
            "SQL passed parser and PostgreSQL "
            "validation."
        ),
        errors=[],
        warnings=warnings,
        details=details,
    )


# ============================================================
# SIMPLE BOOLEAN API
# ============================================================

def is_valid_sql(
    sql: str,
    engine: Optional[Engine] = None,
) -> bool:
    """
    Simple True/False validation API.
    """

    result = validate_sql(
        sql=sql,
        engine=engine,
        run_explain=engine is not None,
    )

    return result["valid"]